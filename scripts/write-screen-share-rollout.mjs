import { writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

export function renderScreenShareRollout(value) {
  const enabled = value === "true";
  return `// Generated by scripts/write-screen-share-rollout.mjs before Electron compile.
// Tracked default stays fail-closed for development, PR, and release builds.
export const NATIVE_SCREEN_AUDIO_ENABLED = ${String(enabled)} as boolean;
`;
}

async function main() {
  await writeFile(
    new URL("../electron/screen-share-rollout.ts", import.meta.url),
    renderScreenShareRollout(process.env.BAKBAK_NATIVE_SCREEN_AUDIO_CANDIDATE),
    "utf8",
  );
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  await main();
}
